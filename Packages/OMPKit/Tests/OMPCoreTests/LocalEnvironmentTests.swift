import XCTest
@testable import OMPCore

/// Reader, writer, discovery and selection of local environments.
final class LocalEnvironmentTests: XCTestCase {
    private var root: URL!

    override func setUpWithError() throws {
        root = FileManager.default.temporaryDirectory
            .appendingPathComponent("omp-env-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
    }

    override func tearDownWithError() throws {
        try? FileManager.default.removeItem(at: root)
    }

    private func write(_ text: String, to relative: String) throws -> String {
        let path = root.appendingPathComponent(relative).path
        try FileManager.default.createDirectory(
            atPath: (path as NSString).deletingLastPathComponent, withIntermediateDirectories: true
        )
        try text.write(toFile: path, atomically: true, encoding: .utf8)
        return path
    }

    private func makeRepo(at relative: String) throws -> String {
        let repo = root.appendingPathComponent(relative).path
        try FileManager.default.createDirectory(
            atPath: repo + "/.git", withIntermediateDirectories: true
        )
        return repo
    }

    // MARK: The official layout

    /// The exact file the official editor writes for a simple setup plus one
    /// action, and what parsing it must produce.
    func testOfficialLayoutRoundTrip() throws {
        let official = """
        # THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
        version = 1
        name = "local"

        [setup]
        script = "npm install"

        [setup.darwin]
        script = "pnpm install"

        [[actions]]
        name = "Run"
        icon = "run"
        command = "npm start"
        platform = "darwin"

        """
        let environment = LocalEnvironment(
            name: "local",
            setup: LocalEnvironmentScript(
                script: "npm install",
                overrides: [.darwin: "pnpm install"]
            ),
            actions: [LocalEnvironmentAction(name: "Run", icon: "run", command: "npm start", platform: "darwin")]
        )
        XCTAssertEqual(LocalEnvironmentTOML.emit(environment), official)

        let parsed = try LocalEnvironmentTOML.parse(official)
        XCTAssertEqual(parsed, environment)
    }

    /// A minimal file with an empty default setup, no cleanup and no actions.
    func testEmptySetupAlwaysWritten() throws {
        let environment = LocalEnvironment(name: "bare")
        XCTAssertEqual(
            LocalEnvironmentTOML.emit(environment),
            """
            # THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
            version = 1
            name = "bare"

            [setup]
            script = ""

            """
        )
        XCTAssertEqual(try LocalEnvironmentTOML.parse(LocalEnvironmentTOML.emit(environment)), environment)
    }

    /// Cleanup and its platform tables, plus override ordering and the blank
    /// lines between platform tables.
    func testCleanupSectionRoundTrip() throws {
        let environment = LocalEnvironment(
            name: "web",
            setup: LocalEnvironmentScript(script: "make"),
            cleanup: LocalEnvironmentScript(
                script: "make clean",
                overrides: [.linux: "rm -rf .cache", .win32: "rmdir /s .cache"]
            ),
            actions: [
                LocalEnvironmentAction(name: "Test", icon: "test", command: "make test"),
                LocalEnvironmentAction(name: "Debug", icon: "debug", command: "make debug", platform: "linux"),
            ]
        )
        let expected = """
        # THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
        version = 1
        name = "web"

        [setup]
        script = "make"

        [cleanup]
        script = "make clean"

        [cleanup.linux]
        script = "rm -rf .cache"

        [cleanup.win32]
        script = "rmdir /s .cache"

        [[actions]]
        name = "Test"
        icon = "test"
        command = "make test"

        [[actions]]
        name = "Debug"
        icon = "debug"
        command = "make debug"
        platform = "linux"

        """
        XCTAssertEqual(LocalEnvironmentTOML.emit(environment), expected)
        XCTAssertEqual(try LocalEnvironmentTOML.parse(expected), environment)
    }

    // MARK: Escapes and multi-line scripts

    func testQuotingStyles() {
        // The official writer always emits single-line basic strings
        // (JSON.stringify encoding); multi-line scripts keep `\n` escapes.
        XCTAssertEqual(LocalEnvironmentTOML.quote("npm install"), "\"npm install\"")
        XCTAssertEqual(LocalEnvironmentTOML.quote("say \"hi\""), "\"say \\\"hi\\\"\"")
        XCTAssertEqual(LocalEnvironmentTOML.quote("a\tb\nc"), "\"a\\tb\\nc\"")
        XCTAssertEqual(
            LocalEnvironmentTOML.quote("npm install\nnpm test"),
            "\"npm install\\nnpm test\""
        )
        XCTAssertEqual(
            LocalEnvironmentTOML.quote("echo '''\necho done"),
            "\"echo '''\\necho done\""
        )
        XCTAssertEqual(LocalEnvironmentTOML.quote("C:\\path"), "\"C:\\\\path\"")
        // Carriage returns are normalized before encoding.
        XCTAssertEqual(LocalEnvironmentTOML.quote("a\r\nb"), "\"a\\nb\"")
    }

    func testEscapesRoundTripThroughFiles() throws {
        let script = "echo \"a b\"\nprintf '%s\\n' \"$HOME\"\n"
        let environment = LocalEnvironment(
            name: "escapes",
            setup: LocalEnvironmentScript(script: script),
            actions: [LocalEnvironmentAction(name: "Run \"it\"", icon: nil, command: script)]
        )
        let text = LocalEnvironmentTOML.emit(environment)
        let path = try write(text, to: "escapes.toml")
        let file = LocalEnvironmentDiscovery.readFile(at: path)
        XCTAssertEqual(file.environment, environment)
    }

    /// A reader of the official writer's multi-line output gets the original
    /// script back, newlines and all.
    func testMultiLineLiteralParsing() throws {
        let text = """
        # THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
        version = 1
        name = "multi"

        [setup]
        script = '''
        pip install -r requirements.txt
        npm install
        ./run/setup.sh'''

        """
        let parsed = try LocalEnvironmentTOML.parse(text)
        XCTAssertEqual(parsed.setup.script, "pip install -r requirements.txt\nnpm install\n./run/setup.sh")
    }

    func testMultiLineBasicParsingWithTripleQuotes() throws {
        // A literal `"""` inside the script is escaped, as a hand-written
        // TOML multi-line basic string requires.
        let text = """
        version = 1
        name = "basic"

        [setup]
        script = \"\"\"
        echo \\\"\"\"
        echo done\"\"\"

        """
        let parsed = try LocalEnvironmentTOML.parse(text)
        XCTAssertEqual(parsed.setup.script, "echo \"\"\"\necho done")
    }

    /// A literal script ending in quotes does not eat the closing delimiter.
    func testLiteralEndingInQuotes() throws {
        let text = "name = 'quotes'\n\n[setup]\nscript = '''echo ''''\n"
        let parsed = try LocalEnvironmentTOML.parse(text)
        XCTAssertEqual(parsed.setup.script, "echo '")
    }

    // MARK: Platform override precedence

    func testOverridePrecedence() {
        let script = LocalEnvironmentScript(
            script: "default",
            overrides: [.darwin: "", .linux: "linux-script"]
        )
        XCTAssertEqual(script.resolved(for: .darwin), "default", "empty override means default")
        XCTAssertEqual(script.resolved(for: .linux), "linux-script")
        XCTAssertEqual(script.resolved(for: .win32), "default")
        XCTAssertNil(LocalEnvironmentScript().resolved(for: .darwin), "no script anywhere is nothing to run")
    }

    // MARK: Invalid files

    func testInvalidFilesReportLines() throws {
        let cases: [(String, Int, String)] = [
            ("name = \"x\"\n\n[setup]\nscript = \"a \\q b\"\n", 4, "转义"),
            ("name = \"x\n", 1, "结束引号"),
            ("version = \"x\"\nname = \"x\"\n", 1, "version"),
            ("version = 0\nname = \"x\"\n", 1, "version"),
            ("name\n", 1, "等号"),
            ("name = \"x\"\n[[actions]]\nname = \"run\"\nplatform = \"atari\"\n", 4, "platform"),
            ("[setup]\nname = \"missing top name\"\n", 1, "name"),
        ]
        for (text, line, hint) in cases {
            do {
                _ = try LocalEnvironmentTOML.parse(text)
                XCTFail("expected a parse error for: \(text), hint \(hint)")
            } catch let error as LocalEnvironmentParseError {
                XCTAssertEqual(error.line, line, "line for: \(text)")
                XCTAssertTrue(error.localizedDescription.contains("第 \(line) 行"), "message for \(hint)")
            }
        }
    }

    /// What the official loader drops silently, the reader drops too: actions
    /// missing a name or a command, unknown keys, unknown tables, and icons
    /// outside the known set.
    func testLenientDrops() throws {
        let text = """
        version = 2
        name = "lenient"
        unknownKey = "ignored"

        [unknownTable]
        script = "ignored"

        [setup]
        script = "make"
        note = "ignored"

        [[actions]]
        command = "no name here"

        [[actions]]
        name = "no command here"

        [[actions]]
        name = "Kept"
        icon = "wrench"
        command = "make"

        [[actions]]
        name = "No icon"
        icon = ""
        command = "make all"

        """
        let parsed = try LocalEnvironmentTOML.parse(text)
        XCTAssertEqual(parsed.version, 2)
        XCTAssertEqual(parsed.actions.map(\.name), ["Kept", "No icon"])
        XCTAssertNil(parsed.actions[0].icon, "unknown icon drops to none")
        XCTAssertNil(parsed.cleanup)
    }

    // MARK: Discovery

    func testDiscoveryOrderAndInheritance() throws {
        let repo = try makeRepo(at: "repo")
        try write("name = \"root-env\"\n\n[setup]\nscript = \"\"\n", to: "repo/.codex/environments/b.toml")
        try write("name = \"root-env-a\"\n\n[setup]\nscript = \"\"\n", to: "repo/.codex/environments/a.toml")
        try write("name = \"sub\"\n\n[setup]\nscript = \"\"\n", to: "repo/packages/app/.codex/environments/own.toml")
        // Outside the repository: never discovered.
        try write("name = \"outside\"\n\n[setup]\nscript = \"\"\n", to: ".codex/environments/outside.toml")

        let working = repo + "/packages/app"
        let files = LocalEnvironmentDiscovery.files(inWorkingDirectory: working)

        XCTAssertEqual(files.map(\.fileName), ["own.toml", "a.toml", "b.toml"], "nearest folder first, then file-name order")
        XCTAssertEqual(files[0].inherited, false)
        XCTAssertEqual(files[0].sourceFolderName, nil)
        XCTAssertEqual(files[1].inherited, true)
        XCTAssertEqual(files[1].sourceFolderName, "repo")
        XCTAssertEqual(files[2].sourceFolderName, "repo")
        XCTAssertEqual(files.map(\.displayName), ["sub", "root-env-a", "root-env"])
    }

    func testDiscoveryStopsAtRepositoryRoot() throws {
        let repo = try makeRepo(at: "repo")
        let nested = try makeRepo(at: "repo/vendor/inner")
        try write("name = \"inner\"\n\n[setup]\nscript = \"\"\n", to: "repo/vendor/inner/.codex/environments/i.toml")
        try write("name = \"outer\"\n\n[setup]\nscript = \"\"\n", to: "repo/.codex/environments/o.toml")
        _ = repo

        let files = LocalEnvironmentDiscovery.files(inWorkingDirectory: nested + "/src")
        XCTAssertEqual(files.map(\.fileName), ["i.toml"], "the inner repository bounds the walk")
    }

    func testDiscoveryOutsideRepositoryIsEmpty() throws {
        let folder = root.appendingPathComponent("plain").path
        try FileManager.default.createDirectory(atPath: folder, withIntermediateDirectories: true)
        try write("name = \"x\"\n", to: "plain/.codex/environments/x.toml")
        XCTAssertTrue(LocalEnvironmentDiscovery.files(inWorkingDirectory: folder).isEmpty)
        XCTAssertNil(LocalEnvironmentDiscovery.repositoryRoot(containing: folder))
    }

    func testParseErrorKeepsFileListed() throws {
        let repo = try makeRepo(at: "repo")
        try write("name = \"broken\n", to: "repo/.codex/environments/broken.toml")
        let files = LocalEnvironmentDiscovery.files(inWorkingDirectory: repo)
        XCTAssertEqual(files.count, 1)
        XCTAssertNil(files[0].environment)
        XCTAssertEqual(files[0].parseError?.line, 1)
    }

    // MARK: Selection

    func testSelectionFallbackRules() throws {
        let repo = try makeRepo(at: "repo")
        let only = try write("name = \"only\"\n\n[setup]\nscript = \"\"\n", to: "repo/.codex/environments/only.toml")
        let files = LocalEnvironmentDiscovery.files(inWorkingDirectory: repo)

        XCTAssertEqual(
            LocalEnvironmentDiscovery.selectedPath(projectRoot: repo, files: files, selections: [:]),
            only,
            "a single discovered file is selected by default"
        )

        let other = try write("name = \"other\"\n\n[setup]\nscript = \"\"\n", to: "repo/.codex/environments/other.toml")
        let two = LocalEnvironmentDiscovery.files(inWorkingDirectory: repo)
        XCTAssertNil(
            LocalEnvironmentDiscovery.selectedPath(projectRoot: repo, files: two, selections: [:]),
            "two files and no choice is none"
        )

        XCTAssertEqual(
            LocalEnvironmentDiscovery.selectedPath(projectRoot: repo, files: two, selections: [repo: other]),
            other
        )
        XCTAssertNil(
            LocalEnvironmentDiscovery.selectedPath(projectRoot: repo, files: two, selections: [repo: LocalEnvironmentDiscovery.noneSelection]),
            "the sentinel keeps the explicit none"
        )
        // A choice whose file disappeared falls back to the rules (two files
        // left → no default).
        XCTAssertNil(
            LocalEnvironmentDiscovery.selectedPath(projectRoot: repo, files: two, selections: [repo: "/gone/nowhere.toml"])
        )
    }

    // MARK: Saving

    func testSaveCreatesFoldersAndRejectsConflicts() throws {
        let repo = try makeRepo(at: "repo")
        let environment = LocalEnvironment(name: "fresh", setup: LocalEnvironmentScript(script: "make"))

        // A missing file needs a nil baseline.
        XCTAssertNil(LocalEnvironmentDiscovery.save(environment, toProject: repo, fileName: "fresh", expectedRevision: nil))

        // Saving over it requires the revision that is on disk now.
        let destination = repo + "/.codex/environments/fresh.toml"
        let current = LocalEnvironmentDiscovery.revision(ofFileAt: destination)
        XCTAssertNil(LocalEnvironmentDiscovery.save(environment, toProject: repo, fileName: "fresh", expectedRevision: current))
        XCTAssertNotNil(
            LocalEnvironmentDiscovery.save(environment, toProject: repo, fileName: "fresh", expectedRevision: "0:deadbeef"),
            "a stale revision is a conflict"
        )

        // Any file name gets `.toml`; a path escape through the name is not
        // possible because only the last component is used.
        XCTAssertEqual(LocalEnvironmentDiscovery.sanitizedFileName("../evil"), "evil.toml")
        XCTAssertEqual(LocalEnvironmentDiscovery.sanitizedFileName("plain.toml"), "plain.toml")
    }

    func testDeleteOnlyInsideEnvironments() throws {
        let repo = try makeRepo(at: "repo")
        let path = try write("name = \"x\"\n", to: "repo/.codex/environments/x.toml")
        XCTAssertNil(LocalEnvironmentDiscovery.delete(at: path))
        XCTAssertNil(LocalEnvironmentDiscovery.delete(at: path), "deleting a missing file succeeds")
        XCTAssertNotNil(
            LocalEnvironmentDiscovery.delete(at: repo + "/README.md"),
            "outside .codex/environments nothing may go"
        )
    }

    // MARK: Config resolution and running

    /// The worktree copy wins over the source copy, and both variables reach
    /// the script.
    func testRunUsesWorktreeCopyAndExportsPaths() async throws {
        let source = try makeRepo(at: "source")
        let configPath = try write(
            "name = \"setup\"\n\n[setup]\nscript = \"printf '%s\\n' $CODEX_SOURCE_TREE_PATH $CODEX_WORKTREE_PATH > made.txt\"\n",
            to: "source/.codex/environments/setup.toml"
        )
        let worktree = root.appendingPathComponent("worktree").path
        try FileManager.default.createDirectory(atPath: worktree, withIntermediateDirectories: true)

        let result = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: configPath, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertEqual(result.exitCode, 0, result.output)
        XCTAssertFalse(result.skipped)
        let made = try String(contentsOfFile: worktree + "/made.txt", encoding: .utf8)
        XCTAssertTrue(
            made.hasPrefix(LocalEnvironmentDiscovery.standardize(source) + "\n" + LocalEnvironmentDiscovery.standardize(worktree)),
            "made: \(made)"
        )
    }

    /// The same relative file in the worktree is the one that runs.
    func testWorktreeCopyWins() async throws {
        let source = try makeRepo(at: "source")
        let configPath = try write(
            "name = \"which\"\n\n[setup]\nscript = \"echo source-copy\"\n",
            to: "source/.codex/environments/which.toml"
        )
        let worktree = root.appendingPathComponent("wt").path
        try FileManager.default.createDirectory(
            atPath: worktree + "/.codex/environments", withIntermediateDirectories: true
        )
        try "name = \"which\"\n\n[setup]\nscript = \"echo worktree-copy\"\n"
            .write(toFile: worktree + "/.codex/environments/which.toml", atomically: true, encoding: .utf8)

        let result = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: configPath, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertTrue(result.output.contains("worktree-copy"), "got: \(result.output)")
        XCTAssertFalse(result.output.contains("source-copy"))
    }

    func testResolvedConfigPrefersWorktreeCopy() throws {
        let source = root.appendingPathComponent("src").path
        let config = source + "/.codex/environments/e.toml"
        let worktree = root.appendingPathComponent("wt").path
        let expected = LocalEnvironmentDiscovery.standardize(worktree) + "/.codex/environments/e.toml"

        // No worktree copy → the source file is used.
        XCTAssertEqual(
            LocalEnvironmentDiscovery.resolvedConfig(configPath: config, sourceRoot: source, worktreeRoot: worktree),
            LocalEnvironmentDiscovery.standardize(config)
        )
        // A worktree copy → that copy.
        try FileManager.default.createDirectory(
            atPath: (expected as NSString).deletingLastPathComponent, withIntermediateDirectories: true
        )
        try "x".write(toFile: expected, atomically: true, encoding: .utf8)
        XCTAssertEqual(
            LocalEnvironmentDiscovery.resolvedConfig(configPath: config, sourceRoot: source, worktreeRoot: worktree),
            expected
        )
        // A config outside the source tree is used as-is.
        let elsewhere = root.appendingPathComponent("elsewhere.toml").path
        try "x".write(toFile: elsewhere, atomically: true, encoding: .utf8)
        XCTAssertEqual(
            LocalEnvironmentDiscovery.resolvedConfig(configPath: elsewhere, sourceRoot: source, worktreeRoot: worktree),
            LocalEnvironmentDiscovery.standardize(elsewhere)
        )
    }

    func testRunFailuresAndSkips() async throws {
        let source = try makeRepo(at: "source")
        let worktree = root.appendingPathComponent("wt").path
        try FileManager.default.createDirectory(atPath: worktree, withIntermediateDirectories: true)

        // Non-zero exit: the output comes back, not swallowed.
        let failing = try write(
            "name = \"fail\"\n\n[setup]\nscript = \"echo boom\\nexit 3\"\n",
            to: "source/.codex/environments/fail.toml"
        )
        let failed = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: failing, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertEqual(failed.exitCode, 3)
        XCTAssertEqual(failed.output, "boom\n", "output verbatim, no head/tail duplication")

        // An environment with no script for this platform is skipped.
        let empty = try write(
            "name = \"empty\"\n\n[setup]\nscript = \"\"\n\n[cleanup]\nscript = \"echo bye\"\n",
            to: "source/.codex/environments/empty.toml"
        )
        let skippedSetup = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: empty, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertTrue(skippedSetup.skipped)
        XCTAssertEqual(skippedSetup.exitCode, 0)
        let ranCleanup = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .cleanup, configPath: empty, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertFalse(ranCleanup.skipped, "output: \(ranCleanup.output)")
        XCTAssertTrue(ranCleanup.output.contains("bye"), "output: \(ranCleanup.output)")

        // No file at all is skipped, not failed — a worktree without the
        // environment simply has nothing to clean up.
        let missing = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .cleanup, configPath: root.appendingPathComponent("nope.toml").path,
            sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertTrue(missing.skipped)

        // A config that does not parse is a failure with the line number.
        let broken = try write("name = \"broken\n", to: "source/.codex/environments/broken.toml")
        let invalid = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: broken, sourceRoot: source, worktreeRoot: worktree
        )
        XCTAssertFalse(invalid.skipped)
        XCTAssertNotEqual(invalid.exitCode, 0)
        XCTAssertTrue(invalid.output.contains("第 1 行"))
    }

    /// A fake runner keeps resolution logic testable without a shell; the
    /// real runner is exercised by the tests above.
    func testRunnerReceivesEnvironment() async throws {
        let source = try makeRepo(at: "source")
        let configPath = try write(
            "name = \"env\"\n\n[setup]\nscript = \"make\"\n",
            to: "source/.codex/environments/env.toml"
        )
        let worktree = root.appendingPathComponent("wt").path
        final class Recording: LocalEnvironmentRunning {
            private let lock = NSLock()
            private var stored: (script: String, cwd: String, environment: [String: String])?
            var received: (script: String, cwd: String, environment: [String: String])? {
                lock.withLock { stored }
            }
            func run(script: String, cwd: String, environment: [String: String], timeout: Double, outputCap: Int) async -> (exitCode: Int32, output: String) {
                lock.withLock { self.stored = (script, cwd, environment) }
                return (0, "")
            }
        }
        let recorder = Recording()
        let result = await LocalEnvironmentDiscovery.runLocalEnvironmentScript(
            .setup, configPath: configPath, sourceRoot: source, worktreeRoot: worktree, runner: recorder
        )
        XCTAssertEqual(result.exitCode, 0)
        let received = try XCTUnwrap(recorder.received)
        XCTAssertEqual(received.script, "make")
        XCTAssertEqual(received.cwd, LocalEnvironmentDiscovery.standardize(worktree))
        XCTAssertEqual(received.environment["CODEX_SOURCE_TREE_PATH"], LocalEnvironmentDiscovery.standardize(source))
        XCTAssertEqual(received.environment["CODEX_WORKTREE_PATH"], LocalEnvironmentDiscovery.standardize(worktree))
    }
